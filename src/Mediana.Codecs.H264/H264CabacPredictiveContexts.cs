        public static H264CabacContext[] Create(int qp, int cabacInitIdc)
        {
            ArgumentOutOfRangeException.ThrowIfNegative(cabacInitIdc);
            ArgumentOutOfRangeException.ThrowIfGreaterThan(cabacInitIdc, 2);
            H264CabacContext[] contexts = new H264CabacContext[ContextCount];
            int offset = cabacInitIdc * ContextCount * 2;
            for (int index = 0; index < contexts.Length; index++)
            {
                contexts[index] = H264CabacContext.Initialize(InitialValues[offset + index * 2], InitialValues[offset + index * 2 + 1], qp);
            }
            return contexts;
        }

        public static int GetIndex(int contextIndex) => contextIndex switch
        {
            >= 11 and <= 23 => contextIndex - 11,
            >= 40 and <= 275 => contextIndex - 40 + 13,
            >= 399 and <= 401 => contextIndex - 399 + 249,
            _ => throw new ArgumentOutOfRangeException(nameof(contextIndex), "The context is not an initialized progressive P-slice context.")
        };
