        public static H264CabacContext[] Create(int qp)
        {
            H264CabacContext[] contexts = new H264CabacContext[InitialValues.Length / 2];
            for (int index = 0; index < contexts.Length; index++)
            {
                contexts[index] = H264CabacContext.Initialize(InitialValues[index * 2], InitialValues[index * 2 + 1], qp);
            }
            return contexts;
        }

        public static int GetIndex(int contextIndex) => contextIndex switch
        {
            >= 3 and <= 10 => contextIndex - 3,
            >= 60 and <= 275 => contextIndex - 60 + 8,
            >= 399 and <= 401 => contextIndex - 399 + 224,
            _ => throw new ArgumentOutOfRangeException(nameof(contextIndex), "The context is not an initialized progressive I-slice context.")
