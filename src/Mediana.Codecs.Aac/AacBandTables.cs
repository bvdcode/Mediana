namespace Mediana.Codecs.Aac
{
    // ISO/IEC 13818-7:2004, tables 33 and 45–57.
    internal static class AacBandTables
    {
        public static ReadOnlySpan<int> Get(int frequencyIndex, bool shortWindow)
        {
            if (shortWindow)
            {
                return frequencyIndex switch
                {
                    0 or 1 or 2 => [0, 4, 8, 12, 16, 20, 24, 32, 40, 48, 64, 92, 128],
                    3 or 4 or 5 => [0, 4, 8, 12, 16, 20, 28, 36, 44, 56, 68, 80, 96, 112, 128],
                    6 or 7 => [0, 4, 8, 12, 16, 20, 24, 28, 36, 44, 52, 64, 76, 92, 108, 128],
                    8 or 9 or 10 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 40, 48, 60, 72, 88, 108, 128],
                    11 => [0, 4, 8, 12, 16, 20, 24, 28, 36, 44, 52, 60, 72, 88, 108, 128],
                    _ => throw new NotSupportedException("The AAC sampling frequency has no supported short-window band table.")
                };
            }
            return frequencyIndex switch
            {
                0 or 1 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40, 44, 48, 52, 56, 64, 72, 80, 88, 96, 108, 120, 132, 144, 156, 172, 188, 212, 240, 276, 320, 384, 448, 512, 576, 640, 704, 768, 832, 896, 960, 1024],
                2 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40, 44, 48, 52, 56, 64, 72, 80, 88, 100, 112, 124, 140, 156, 172, 192, 216, 240, 268, 304, 344, 384, 424, 464, 504, 544, 584, 624, 664, 704, 744, 784, 824, 864, 904, 944, 984, 1024],
                3 or 4 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40, 48, 56, 64, 72, 80, 88, 96, 108, 120, 132, 144, 160, 176, 196, 216, 240, 264, 292, 320, 352, 384, 416, 448, 480, 512, 544, 576, 608, 640, 672, 704, 736, 768, 800, 832, 864, 896, 928, 1024],
                5 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40, 48, 56, 64, 72, 80, 88, 96, 108, 120, 132, 144, 160, 176, 196, 216, 240, 264, 292, 320, 352, 384, 416, 448, 480, 512, 544, 576, 608, 640, 672, 704, 736, 768, 800, 832, 864, 896, 928, 960, 992, 1024],
                6 or 7 => [0, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40, 44, 52, 60, 68, 76, 84, 92, 100, 108, 116, 124, 136, 148, 160, 172, 188, 204, 220, 240, 260, 284, 308, 336, 364, 396, 432, 468, 508, 552, 600, 652, 704, 768, 832, 896, 960, 1024],
                8 or 9 or 10 => [0, 8, 16, 24, 32, 40, 48, 56, 64, 72, 80, 88, 100, 112, 124, 136, 148, 160, 172, 184, 196, 212, 228, 244, 260, 280, 300, 320, 344, 368, 396, 424, 456, 492, 532, 572, 616, 664, 716, 772, 832, 896, 960, 1024],
                11 => [0, 12, 24, 36, 48, 60, 72, 84, 96, 108, 120, 132, 144, 156, 172, 188, 204, 220, 236, 252, 268, 288, 308, 328, 348, 372, 396, 420, 448, 476, 508, 544, 580, 620, 664, 712, 764, 820, 880, 944, 1024],
                _ => throw new NotSupportedException("The AAC sampling frequency has no supported long-window band table.")
            };
        }

        public static int TnsLimit(int frequencyIndex, bool shortWindow)
        {
            ReadOnlySpan<int> limits = shortWindow
                ? [9, 9, 10, 14, 14, 14, 14, 14, 14, 14, 14, 14]
                : [31, 31, 34, 40, 42, 51, 46, 46, 42, 42, 42, 39];
            return limits[frequencyIndex];
        }
    }
}
